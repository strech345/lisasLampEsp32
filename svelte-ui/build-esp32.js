#!/usr/bin/env node

import fs from "fs";
import path from "path";
import { promisify } from "util";
import { gzip } from "zlib";

// Benötigt Node 20.11+
const __dirname = import.meta.dirname;

const gzipAsync = promisify(gzip);

const DIST_DIR = path.join(__dirname, "dist");
const DATA_DIR = path.join(__dirname, "..", "data");
const GZIP_EXT = ".gzip";

/**
 * Komprimiert eine Datei mit gzip (Level 9).
 * @returns {Promise<boolean>} true bei Erfolg, sonst false
 */
async function compressFile(inputPath, outputPath) {
  try {
    const data = await fs.promises.readFile(inputPath);
    const compressed = await gzipAsync(data, { level: 9 });
    await fs.promises.writeFile(outputPath, compressed);

    const originalSize = data.length;
    const compressedSize = compressed.length;
    const savings = originalSize
      ? (((originalSize - compressedSize) / originalSize) * 100).toFixed(1)
      : "0.0";

    console.log(
      `✓ ${path.basename(inputPath)} -> ${path.basename(
        outputPath
      )} (${originalSize}B -> ${compressedSize}B, ${savings}% savings)`
    );
    return true;
  } catch (error) {
    console.error(`✗ Failed to compress ${inputPath}:`, error.message);
    return false;
  }
}

async function processFiles() {
  console.log("🔨 Processing Svelte build for ESP32...\n");

  // Check if dist directory exists
  if (!fs.existsSync(DIST_DIR)) {
    console.error('❌ Dist directory not found. Run "npm run build" first.');
    process.exit(1);
  }

  // index.prod.html ist die Captive-Portal-kompatible Vorlage (kein type="module", kein CDN)
  const indexProdSrc = path.join(__dirname, "index.prod.html");
  if (!fs.existsSync(indexProdSrc)) {
    console.error("❌ index.prod.html nicht gefunden");
    process.exit(1);
  }

  // Ensure data directory exists
  fs.mkdirSync(DATA_DIR, { recursive: true });

  // Remove outdated files that are no longer generated by the build
  const outdatedFiles = [
    path.join(DATA_DIR, `app.css${GZIP_EXT}`),
  ];
  
  outdatedFiles.forEach(file => {
    if (fs.existsSync(file)) {
      try {
        fs.unlinkSync(file);
        console.log(`🗑️  Removed outdated file: ${path.basename(file)}`);
      } catch (err) {
        console.warn(`⚠️  Could not remove outdated file: ${path.basename(file)}`);
      }
    }
  });

  const jobs = [
    {
      src: indexProdSrc,
      dest: path.join(DATA_DIR, `index.html${GZIP_EXT}`),
      required: true,
    },
    {
      src: path.join(DIST_DIR, "app.js"),
      dest: path.join(DATA_DIR, `app.js${GZIP_EXT}`),
      required: true,
    },
    {
      // Optional: pico.min.css, falls in data/ vorhanden
      src: path.join(DATA_DIR, "pico.min.css"),
      dest: path.join(DATA_DIR, `pico.min.css${GZIP_EXT}`),
      required: false,
    },
  ];

  let processedCount = 0;
  let failedCount = 0;

  for (const job of jobs) {
    if (!fs.existsSync(job.src)) {
      if (job.required) {
        console.error(`❌ ${path.basename(job.src)} nicht gefunden`);
        failedCount++;
      } else {
        console.log(`⚠️  ${path.basename(job.src)} not found, skipping...`);
      }
      continue;
    }

    if (await compressFile(job.src, job.dest)) {
      processedCount++;
    } else {
      failedCount++;
    }
  }

  if (failedCount > 0) {
    console.error(
      `\n❌ ${failedCount} file(s) failed, ${processedCount} processed.`
    );
    process.exit(1);
  }

  console.log(`\n✅ Processed ${processedCount} files successfully!`);
  console.log(
    "📁 Files are ready in the data/ directory for ESP32 deployment."
  );

  // List all compressed files in data directory
  console.log(`\n📋 Compressed files in data/:`);
  fs.readdirSync(DATA_DIR)
    .filter((f) => f.endsWith(GZIP_EXT))
    .forEach((file) => {
      const size = fs.statSync(path.join(DATA_DIR, file)).size;
      console.log(`   ${file} (${size} bytes)`);
    });
}

// Run the script
processFiles().catch((error) => {
  console.error("❌ Build script failed:", error);
  process.exit(1);
});